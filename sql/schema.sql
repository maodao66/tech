CREATE TABLE IF NOT EXISTS tf_batch_job_log (
  id              varchar(64)   NOT NULL COMMENT '主键',
  job_code        varchar(64)   NOT NULL COMMENT '批处理编码：行业同步/贷款同步/任务生成/结果同步/机构用户同步等',
